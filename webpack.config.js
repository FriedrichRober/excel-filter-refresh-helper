/* eslint-disable no-undef */

const devCerts = require("office-addin-dev-certs");
const CopyWebpackPlugin = require("copy-webpack-plugin");
const HtmlWebpackPlugin = require("html-webpack-plugin");
const fs = require("fs");
const webpack = require("webpack");

// The add-in version shown in the task pane comes from manifest.xml, the
// version Office itself uses, so it only has to be bumped in one place.
function readManifestVersion() {
  const manifest = fs.readFileSync("./manifest.xml", "utf8");
  const match = manifest.match(/<Version>([^<]+)<\/Version>/);
  if (!match) {
    throw new Error("Could not find <Version> in manifest.xml.");
  }
  return match[1].trim();
}

const urlDev = "https://localhost:3000/";
// Public HTTPS base URL of the deployed add-in (e.g. the GitHub Pages URL),
// ending with "/". Required for production builds.
const urlProd = process.env.ADDIN_BASE_URL;

async function getHttpsOptions() {
  const httpsOptions = await devCerts.getHttpsServerOptions();
  return { ca: httpsOptions.ca, key: httpsOptions.key, cert: httpsOptions.cert };
}

module.exports = async (env, options) => {
  const dev = options.mode === "development";

  if (!dev && !/^https:\/\/.+\/$/.test(urlProd || "")) {
    throw new Error('Set ADDIN_BASE_URL to the HTTPS deployment URL ending with "/" for production builds.');
  }
  const config = {
    devtool: "source-map",
    entry: {
      polyfill: ["core-js/stable", "regenerator-runtime/runtime"],
      taskpane: ["./src/taskpane/taskpane.js", "./src/taskpane/taskpane.html"],
    },
    output: {
      clean: true,
    },
    resolve: {
      extensions: [".html", ".js"],
    },
    module: {
      rules: [
        {
          test: /\.js$/,
          exclude: /node_modules/,
          use: {
            loader: "babel-loader",
          },
        },
        {
          test: /\.html$/,
          exclude: /node_modules/,
          use: "html-loader",
        },
        {
          test: /\.(png|jpg|jpeg|gif|ico)$/,
          type: "asset/resource",
          generator: {
            filename: "assets/[name][ext][query]",
          },
        },
      ],
    },
    plugins: [
      new webpack.DefinePlugin({
        __ADDIN_VERSION__: JSON.stringify(readManifestVersion()),
        // Build moment (UTC ms), so each deploy can be told apart in the task pane.
        __BUILD_TIME__: JSON.stringify(Date.now()),
      }),
      new HtmlWebpackPlugin({
        filename: "taskpane.html",
        template: "./src/taskpane/taskpane.html",
        chunks: ["polyfill", "taskpane"],
      }),
      new CopyWebpackPlugin({
        patterns: [
          {
            from: "assets/*",
            to: "assets/[name][ext][query]",
          },
          {
            from: "manifest*.xml",
            to: "[name]" + "[ext]",
            transform(content) {
              if (dev) {
                return content;
              } else {
                return content.toString().replace(new RegExp(urlDev, "g"), urlProd);
              }
            },
          },
        ],
      }),
    ],
    devServer: {
      headers: {
        "Access-Control-Allow-Origin": "*",
      },
      server: {
        type: "https",
        options: env.WEBPACK_BUILD || options.https !== undefined ? options.https : await getHttpsOptions(),
      },
      port: process.env.npm_package_config_dev_server_port || 3000,
    },
  };

  return config;
};
